CREATE TABLE customer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode            VARCHAR(20)   NOT NULL UNIQUE,
    nama            VARCHAR(120)  NOT NULL,
    kota            VARCHAR(60)   NOT NULL,
    segmen          VARCHAR(20)   NOT NULL,
    termin_hari     INT           NOT NULL,
    limit_kredit    DECIMAL(18,2) NOT NULL
);

CREATE TABLE produk (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode            VARCHAR(20)   NOT NULL UNIQUE,
    nama            VARCHAR(120)  NOT NULL,
    satuan          VARCHAR(20)   NOT NULL,
    harga_jual      DECIMAL(18,2) NOT NULL,
    aktif           BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE sales_order (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomor           VARCHAR(30)   NOT NULL UNIQUE,
    tanggal         DATE          NOT NULL,
    customer_id     BIGINT        NOT NULL REFERENCES customer(id),
    sumber          VARCHAR(10)   NOT NULL,          -- APLIKASI | IMPOR
    diskon_standar  DECIMAL(5,2)  NOT NULL,          -- persen, dari segmen customer
    diskon_tambahan DECIMAL(5,2),                    -- persen, diajukan sales
    total           DECIMAL(18,2) NOT NULL,
    status          VARCHAR(30)   NOT NULL,
    alasan_status   VARCHAR(255),
    disetujui_oleh  VARCHAR(60),
    catatan         VARCHAR(255)
);

CREATE TABLE sales_order_item (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id  BIGINT        NOT NULL REFERENCES sales_order(id),
    produk_id       BIGINT        NOT NULL REFERENCES produk(id),
    qty             INT           NOT NULL,
    harga           DECIMAL(18,2) NOT NULL
);

CREATE TABLE faktur (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nomor           VARCHAR(30)   NOT NULL UNIQUE,
    tanggal         DATE          NOT NULL,
    jatuh_tempo     DATE          NOT NULL,
    customer_id     BIGINT        NOT NULL REFERENCES customer(id),
    sales_order_id  BIGINT        NOT NULL UNIQUE REFERENCES sales_order(id),
    total           DECIMAL(18,2) NOT NULL,
    status          VARCHAR(20)   NOT NULL           -- BELUM_LUNAS | LUNAS
);

-- penomoran dokumen: SO/<tahun>/<bulan>/<urut>, INV/<tahun>/<bulan>/<urut>
CREATE SEQUENCE nomor_so_seq START WITH 101;
CREATE SEQUENCE nomor_faktur_seq START WITH 101;
